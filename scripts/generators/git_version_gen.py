#!/usr/bin/env python3
"""
Generate a header with two version strings for the binary-signature
.mcu_info block:

  TLK_SDK_GIT_VERSION - the *original* Telink UniSDK version, as decided by
      scripts/tlkpkg/sdk_version.py (the single source of those rules): the
      SDK's version.yaml, plus git build metadata in a source checkout,
      e.g. 0.3.0+5.gabc1234.dirty (frozen as such into an export).

  TLK_APP_GIT_VERSION - the user application's own version: always
      `git describe` in the application's source directory, which is
      expected to be a separate, live git repository.

Re-run on every build (see cmake/modules/version.cmake) so both versions
always reflect the current source trees, including a dirty marker for
uncommitted changes. The output file is only rewritten when its content
actually changes, so an unchanged version does not force a rebuild.

Author: Telink Semiconductor
License: Apache-2.0
"""

import argparse
import subprocess
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "tlkpkg"))
import sdk_version  # noqa: E402


def git_describe(repo_dir):
    try:
        out = subprocess.run(
            ["git", "-C", str(repo_dir), "describe", "--tags", "--always", "--dirty"],
            stdout=subprocess.PIPE,
            stderr=subprocess.DEVNULL,
            check=True,
        )
        return out.stdout.decode().strip()
    except (subprocess.CalledProcessError, FileNotFoundError, OSError):
        return "unknown"


def get_app_version(repo_dir):
    return git_describe(repo_dir)


def render_define(name, value, max_len):
    # Reserve one byte for the NUL terminator, since this is placed in a
    # fixed-size flash field (see tlk_mcu_info.c) that must never overflow.
    value = value[: max(max_len - 1, 0)]
    return f'#define {name} "{value}"\n'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", required=True, help="Path of the header file to generate")
    parser.add_argument("--sdk-repo", required=True, help="Path to the SDK root (TELINK_BASE)")
    parser.add_argument("--sdk-max-len", type=int, required=True)
    parser.add_argument("--app-repo", required=True, help="Path to the application's git repository")
    parser.add_argument("--app-max-len", type=int, required=True)
    args = parser.parse_args()

    try:
        sdk = sdk_version.resolve(Path(args.sdk_repo)).display
    except sdk_version.SdkVersionError as exc:
        print(f"git_version_gen.py: {exc}", file=sys.stderr)
        return 1
    app_version = get_app_version(Path(args.app_repo))

    content = (
        "/* Auto-generated by git_version_gen.py - do not edit by hand. */\n"
        "#pragma once\n"
        + render_define("TLK_SDK_GIT_VERSION", sdk, args.sdk_max_len)
        + render_define("TLK_APP_GIT_VERSION", app_version, args.app_max_len)
    )

    output_path = Path(args.output)
    if output_path.exists() and output_path.read_text() == content:
        return 0

    output_path.write_text(content)
    return 0


if __name__ == "__main__":
    sys.exit(main())
